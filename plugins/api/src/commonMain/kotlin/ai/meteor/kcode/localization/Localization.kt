@Composable
fun protectionDescription(protection: SettingsProtection): String = text(
    when (protection) {
        SettingsProtection.AndroidKeystore -> LocalizedText("protection_android")
        SettingsProtection.DesktopAppData -> LocalizedText("protection_desktop")
        SettingsProtection.Transient -> LocalizedText("protection_transient")
    },
)
